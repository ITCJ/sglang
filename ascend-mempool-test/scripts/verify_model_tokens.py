"""Save exact chat input IDs and compare ordinary/formal sparse PD token output.

Run prepare once with the deployed tokenizer, then reuse that file for every
server run. This small arithmetic sanity gate supplements model acceptance.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import time
import urllib.request
from pathlib import Path
from typing import Any


def prepare(model: Path, *, quick: bool = False) -> dict[str, Any]:
    from transformers import AutoTokenizer

    tokenizer = AutoTokenizer.from_pretrained(str(model), trust_remote_code=True)
    marker = "TICKET10_PADDING_MARKER"
    rendered = tokenizer.apply_chat_template(
        [
            dict(
                role="user",
                content=(
                    f"Ignore the reference padding below.\n{marker}\nEnd of padding.\n"
                    "Compute 17 + 25. Give one short English sentence explaining the "
                    "addition, and finish with 'Answer: <number>'."
                ),
            )
        ],
        tokenize=False,
        add_generation_prompt=True,
        enable_thinking=False,
    )
    if rendered.count(marker) != 1:
        raise ValueError("chat template must retain the padding marker exactly once")
    before, after = rendered.split(marker)
    prefix = tokenizer.encode(before, add_special_tokens=False)
    suffix = tokenizer.encode(after, add_special_tokens=False)
    padding = tokenizer.encode(" Reference padding.", add_special_tokens=False)
    if not padding:
        raise ValueError("tokenizer produced empty padding")
    cases = []
    # D's first forward sees prompt length + the token already generated by P.
    for length in (1024, 2047, 2048, 3072):
        count = length - len(prefix) - len(suffix)
        if count < 0:
            raise ValueError("chat template exceeds the requested test length")
        ids = prefix + (padding * (count // len(padding) + 1))[:count] + suffix
        cases.append(
            dict(
                name=f"prompt_{length}",
                input_ids=ids,
                max_new_tokens=128,
                rendered_input=tokenizer.decode(ids),
            )
        )
    if quick:
        cases = []
        for expression, answer in (("17 + 25", 42), ("9 * 7", 63), ("100 - 16", 84)):
            rendered = tokenizer.apply_chat_template(
                [
                    dict(
                        role="user",
                        content=(
                            f"Compute {expression}. Give one short English sentence explaining "
                            "the calculation, and finish with 'Answer: <number>'."
                        ),
                    )
                ],
                tokenize=False,
                add_generation_prompt=True,
                enable_thinking=False,
            )
            # Some tokenizers return BatchEncoding when chat tokenization is enabled.
            # Match the full suite's explicit text -> token IDs path for JSON fixtures.
            ids = tokenizer.encode(rendered, add_special_tokens=False)
            if not 0 < len(ids) <= 512:
                raise ValueError("quick chat input must fit within 512 tokens")
            cases.append(
                dict(
                    name=f"answer_{answer}",
                    input_ids=ids,
                    max_new_tokens=128,
                    expected_answer=answer,
                    rendered_input=tokenizer.decode(ids),
                )
            )
    zero = dict(cases[0], name="zero_decode", max_new_tokens=1)
    patterns = (
        "config.json",
        "quant_model_description.json",
        "tokenizer*",
        "special_tokens_map.json",
        "added_tokens.json",
        "chat_template*",
        "generation_config.json",
        "vocab.*",
        "merges.txt",
    )
    manifest = {
        path.name: hashlib.sha256(path.read_bytes()).hexdigest()
        for pattern in patterns
        for path in sorted(model.glob(pattern))
        if path.is_file()
    }
    return dict(
        model_path=str(model.resolve()),
        manifest=manifest,
        chat_options=dict(enable_thinking=False, add_generation_prompt=True),
        sampling_params=dict(temperature=0, top_p=1, top_k=1),
        cases=[zero] + cases,
    )


def check_response(case: dict[str, Any], response: dict[str, Any]) -> None:
    meta = response["meta_info"]
    ids = response.get("output_ids")
    if not isinstance(ids, list) or not ids or any(type(i) is not int for i in ids):
        raise ValueError(f"{case['name']}: missing output token IDs")
    if meta["prompt_tokens"] != len(case["input_ids"]):
        raise ValueError(f"{case['name']}: actual prompt length differs from fixture")
    if meta["completion_tokens"] != len(ids):
        raise ValueError(f"{case['name']}: completion count differs from output IDs")
    if case["max_new_tokens"] == 1:
        if len(ids) != 1:
            raise ValueError("zero-decode case must return exactly one token")
        return
    if len(ids) < 2 or meta["finish_reason"]["type"] != "stop":
        raise ValueError(f"{case['name']}: require real decode and a complete answer")
    answer = re.escape(str(case.get("expected_answer", 42)))
    if not re.search(
        rf"\bAnswer:\s*{answer}[.!]?\s*\Z", response.get("text", ""), re.IGNORECASE
    ):
        raise ValueError(
            f"{case['name']}: answer sanity check failed (expected Answer: {answer})"
        )


def run(url: str, fixture: dict[str, Any], report_path: Path) -> None:
    report: dict[str, Any] = dict(status="running", fixture=fixture, results=[])
    try:
        # Different lengths and two passes exercise fresh forwards and slot reuse.
        for cycle in range(2):
            for case in fixture["cases"]:
                payload = dict(
                    input_ids=case["input_ids"],
                    stream=False,
                    sampling_params=dict(
                        fixture["sampling_params"],
                        max_new_tokens=case["max_new_tokens"],
                    ),
                )
                request = urllib.request.Request(
                    url.rstrip("/") + "/generate",
                    data=json.dumps(payload).encode(),
                    headers={"Content-Type": "application/json"},
                )
                start = time.perf_counter()
                with urllib.request.urlopen(request, timeout=1800) as response:
                    result = json.load(response)
                report["results"].append(
                    dict(
                        cycle=cycle,
                        case=case,
                        response=result,
                        elapsed_seconds=time.perf_counter() - start,
                    )
                )
                check_response(case, result)
                print(
                    f"PASS cycle={cycle} {case['name']} tokens={len(result['output_ids'])}",
                    flush=True,
                )
        report["status"] = "passed"
    except Exception as exc:
        report.update(status="failed", error=str(exc))
        raise
    finally:
        report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")


def compare(baseline: dict[str, Any], candidate: dict[str, Any]) -> None:
    if baseline["status"] != "passed" or candidate["status"] != "passed":
        raise ValueError("both runs must pass the response sanity gate")
    if baseline["fixture"] != candidate["fixture"]:
        raise ValueError(
            "fixture differs: compare the same input IDs and model manifest"
        )
    left, right = baseline["results"], candidate["results"]
    if not left or len(left) != len(right):
        raise ValueError("request counts differ or are empty")
    for index, (a, b) in enumerate(zip(left, right)):
        if a["case"] != b["case"] or a.get("cycle") != b.get("cycle"):
            raise ValueError(f"request order differs at {index}")
        check_response(a["case"], a["response"])
        check_response(b["case"], b["response"])
        x, y = a["response"]["output_ids"], b["response"]["output_ids"]
        if x != y:
            pos = next(
                (i for i, (u, v) in enumerate(zip(x, y)) if u != v), min(len(x), len(y))
            )
            raise ValueError(
                f"{a['case']['name']} request {index}: token mismatch at position {pos}; "
                f"baseline={x[pos : pos + 8]}, candidate={y[pos : pos + 8]}"
            )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    prep = commands.add_parser("prepare")
    prep.add_argument("--model-path", type=Path, required=True)
    prep.add_argument("--output", type=Path, required=True)
    prep.add_argument(
        "--quick", action="store_true", help="Three short arithmetic cases"
    )
    execute = commands.add_parser("run")
    execute.add_argument("--url", required=True)
    execute.add_argument("--cases", type=Path, required=True)
    execute.add_argument("--report", type=Path, required=True)
    diff = commands.add_parser("compare")
    diff.add_argument("baseline", type=Path)
    diff.add_argument("candidate", type=Path)
    args = parser.parse_args()
    if args.command == "prepare":
        args.output.write_text(
            json.dumps(
                prepare(args.model_path, quick=args.quick), ensure_ascii=False, indent=2
            )
            + "\n"
        )
    elif args.command == "run":
        run(args.url, json.loads(args.cases.read_text()), args.report)
    else:
        compare(
            json.loads(args.baseline.read_text()),
            json.loads(args.candidate.read_text()),
        )
        print("TOKEN_COMPARISON_PASSED")


if __name__ == "__main__":
    main()
